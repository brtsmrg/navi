"""Build the Navi wordmark (Rubik Black Italic outline + swung red dot) as vector paths.

Outputs public/favicon.svg and src/components/naviWordmark.ts so no font file ships in the app.
Rubik is SIL Open Font License 1.1 (see docs/CREDITS.md)."""
import math, pathlib
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen

ROOT = pathlib.Path(__file__).resolve().parent.parent
font = TTFont(ROOT / "brand/fonts/rubik-900-italic.ttf")
gs, cmap, hmtx = font.getGlyphSet(), font.getBestCmap(), font["hmtx"]
names = [cmap[ord("N")], cmap[ord("a")], cmap[ord("v")], cmap[0x131]]  # N a v dotless-i
x, parts, bounds = 0, [], {}
for n in names:
    pen = SVGPathPen(gs); gs[n].draw(pen)
    bp = BoundsPen(gs); gs[n].draw(bp); bounds[n] = (x, bp.bounds)
    parts.append((x, pen.getCommands())); x += hmtx[n][0]
total = x
ibx = bounds[names[3]]; ix, (x0, y0, x1, y1) = ibx
stem = (x1 - x0) * 0.62
dh, ln = stem * 0.55, stem * 1.5
cx, cy = ix + (x0 + x1) / 2 + stem * 0.28, y1 + stem * 0.85 + dh / 2   # font units, y up
ANG = 22.0  # degrees, tilts the dot up to the right like a rally slide
top, bottom = y1 + stem * 0.85 + dh + ln * 0.2, -10
pad = 90
vb = (-pad, -top - pad * 0.5, total + 2 * pad, (top - bottom) + pad * 1.5)  # y flipped below

def dot(cx_, cy_, ang):
    a = math.radians(ang)
    pts = [(-ln / 2, -dh / 2), (ln / 2, -dh / 2), (ln / 2, dh / 2), (-ln / 2, dh / 2)]
    out = [(cx_ + px * math.cos(a) - py * math.sin(a), cy_ + px * math.sin(a) + py * math.cos(a)) for px, py in pts]
    return "M" + "L".join(f"{p:.1f} {-q:.1f}" for p, q in out) + "Z"

glyph = " ".join(f'<path transform="translate({gx} 0) scale(1 -1)" d="{d}"/>' for gx, d in parts)
RED = "#e41626"
def svg(size_attr="", icon=False):
    if icon:  # square app icon: wordmark centred on black
        s = 512; w = total + 2 * pad; k = (s * 0.70) / w
        ox = s * 0.10 - (-pad) * k; oy = s / 2 + ((top + bottom) / 2) * k * 0  # computed below
        cyc = (top + bottom) / 2
        return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512"><rect width="512" height="512" fill="#000"/>'
                f'<g transform="translate({256 - (total / 2) * k:.2f} {256 + cyc * k:.2f}) scale({k:.5f})" fill="none" stroke="{RED}" stroke-width="{26 / k * 0.17:.1f}" stroke-linejoin="round">{glyph}'
                f'<path d="{dot(cx, cy, ANG)}" fill="{RED}" stroke="none"/></g></svg>')
    return ""
(ROOT / "public/favicon.svg").write_text(svg(icon=True))
import json
ts = ("// Generated by brand/make-wordmark.py. Do not edit.\n"
      f"export const NAVI_VIEWBOX = '{vb[0]:.0f} {vb[1]:.0f} {vb[2]:.0f} {vb[3]:.0f}';\n"
      f"export const NAVI_GLYPHS: [number, string][] = {json.dumps([[gx, d] for gx, d in parts])};\n"
      f"export const NAVI_DOT = {{ cx: {cx:.1f}, cy: {-cy:.1f}, ln: {ln:.1f}, dh: {dh:.1f}, angle: {-ANG} }};\n"
      f"export const NAVI_STROKE = {26 * 0.17:.1f};\n")
(ROOT / "src/components/naviWordmark.ts").write_text(ts)
print("total", total, "stem", round(stem), "dot", round(cx), round(cy), "vb", vb)
